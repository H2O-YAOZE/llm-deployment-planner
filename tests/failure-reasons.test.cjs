'use strict';
const assert=require('node:assert/strict');
const D=require('../data'),E=require('../engine-v5'),C=require('../advisor-core'),R=require('../solver-v5');
const requirements={model:'dsv4f',card:'a910c',precision:'int8',inputK:1000,outputK:1,concurrency:100,ttft:30,speed:50};
const state=C.patchState(E.defaults(D),requirements,D,E);
const r=E.calculate(state,D);
assert.equal(r.ok,true);assert.equal(r.feasible,false);assert.equal(r.chosen,undefined);
assert.equal(r.I,1000000);
assert.ok(r.failureReasons.join(' ').includes('首 Token 时延未达标'));
assert.ok(r.failureReasons.join(' ').includes('106.49 秒'));
assert.ok(r.failureReasons.join(' ').includes('1,000,000 Token'));
assert.ok(r.failureReasons.at(-1).includes('不是实机极限'));
assert.deepEqual(state,C.patchState(E.defaults(D),requirements,D,E),'No silent requirement changes');
const plan=C.evaluateProposals(E.defaults(D),requirements,new Set(),[],D,E).plans[0];
assert.equal(plan.allowed,false);assert.deepEqual(plan.result.failureReasons,r.failureReasons);
const shorter=E.calculate({...state,inputK:80},D);
assert.equal(shorter.feasible,true);assert.deepEqual(shorter.failureReasons,[]);
assert.ok(shorter.cost.capex>0);
const slower=E.calculate({...state,ttft:120},D);
assert.equal(slower.feasible,true);assert.deepEqual(slower.failureReasons,[]);
const speed=E.calculate({...state,inputK:1,speed:10000},D);
assert.equal(speed.feasible,false);assert.ok(speed.failureReasons.some(s=>s.includes('单路生成速度未达标')));
const memory=E.calculate({...state,mode:'reverse',servers:1,slots:1},D);
assert.equal(memory.feasible,false);assert.ok(memory.failureReasons.join(' ').includes('完整模型权重'));
const reverse=R.solve({...state,mode:'reverse',servers:16},D,'concurrency');
assert.equal(reverse.feasible,false);assert.ok(reverse.failureReasons.join(' ').includes('首 Token 时延未达标'));
// Failing validation remains a validation error, never a capacity diagnosis.
const invalid=E.calculate({...state,inputK:2000},D);
assert.equal(invalid.ok,false);assert.deepEqual(E.failureReasons(invalid,state),invalid.errors);
console.log('PASS screenshot, no silent changes, advisor, speed, memory, reverse, validation and feasible alternatives');
