"""Generate the browser/Node catalog from catalog.json. Never edit generated data.js.

Run with --check in validation to catch divergence between data pages and selectors.
"""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]

def build():
    raw=(ROOT/'catalog.json').read_bytes()
    catalog=json.loads(raw)
    for section in ['models','cards','apiPrices']:
        for key,row in catalog[section].items():
            if row['id']!=key:raise ValueError('ID mismatch: '+key)
    for api in catalog['apiPrices'].values():
        for mid in api.get('modelIds',[]):
            if mid not in catalog['models']:raise ValueError('Unknown model mapping: '+mid)
    digest=hashlib.sha256(raw).hexdigest()
    payload=json.dumps(catalog,ensure_ascii=False,separators=(',',':')).replace('<','\\u003c')
    return ('// GENERATED by scripts/build-catalog.py from catalog.json; SHA256 '+digest+'\n'
      "'use strict';\n(function(root){\nconst data="+payload+";\n"
      "root.AppData=data;if(typeof module!=='undefined')module.exports=data;\n"
      "})(typeof window==='undefined'?globalThis:window);\n")

if __name__=='__main__':
    text=build();target=ROOT/'data.js'
    if '--check' in sys.argv:
        if target.read_text('utf-8')!=text:raise SystemExit('Generated data.js is stale')
        print('PASS canonical catalog matches generated runtime data')
    else:
        target.write_text(text,encoding='utf-8');print('Generated data.js')
